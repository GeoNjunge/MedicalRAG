#!/usr/bin/env bash
# Start the local infrastructure simulation with a hard RAM budget (default 6.5 GiB).
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "${ROOT}"

# shellcheck source=../infra/scripts/lib/sim-memory.sh
source "${ROOT}/infra/scripts/lib/sim-memory.sh"

export SIM_MEMORY_ROOT="${ROOT}"
export REDIS_URL="${REDIS_URL:-redis://localhost:6379/0}"

if [[ -f "${ROOT}/.env" ]]; then
  set -a
  # shellcheck disable=SC1091
  source "${ROOT}/.env"
  set +a
fi

PROBE="${SIM_PROBE_WORKER_RSS:-0}"
if [[ "${1:-}" == "--probe" ]]; then
  PROBE=1
  shift
fi

if [[ "${PROBE}" == "1" ]]; then
  echo "Probing single RQ worker RSS (loads full NLP stack once)..."
  docker compose build rq-worker
  docker compose run --rm --no-deps \
    -e WORKER_APP_ENV=dev \
    -e APP_ENV=dev \
    -e SIM_MAX_RQ_WORKERS=1 \
    -e MEDICALRAG_ROOT=/app \
    -e PYTHONPATH=/app:/app/apps/api:/app/ml_core/src \
    --workdir /app/apps/api \
    --entrypoint /app/venv/bin/python3 \
    rq-worker \
    -m app.worker.probe_rss
fi

sim_print_plan

cat > "${ROOT}/.sim-scale.env" <<EOF
# Generated by scripts/sim-up.sh — do not edit by hand.
SIM_BUDGET_GIB=${SIM_BUDGET_GIB}
SIM_MAX_RQ_WORKERS=${SIM_MAX_RQ_WORKERS}
SIM_WORKER_RSS_GIB=${SIM_WORKER_RSS_GIB}
WORKERS=${WORKERS}
RQ_WORKER_MEM_LIMIT=${RQ_WORKER_MEM_LIMIT}
EOF

echo "Starting stack (api=${SIM_API_REPLICAS}, rq-worker=${SIM_MAX_RQ_WORKERS})..."
export WORKERS
export RQ_WORKER_MEM_LIMIT
export SIM_MAX_RQ_WORKERS

docker compose up -d redis postgres
docker compose exec -T redis redis-cli DEL medicalrag:sim:worker_slots >/dev/null 2>&1 || true

docker compose up -d --build --remove-orphans \
  --scale "api=${SIM_API_REPLICAS}" \
  --scale "rq-worker=${SIM_MAX_RQ_WORKERS}" \
  "$@"

echo "Done. Upload jobs beyond worker capacity remain queued in Redis (sequential processing)."
