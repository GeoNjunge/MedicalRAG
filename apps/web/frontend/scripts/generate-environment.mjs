#!/usr/bin/env node
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');
const isProd = process.argv.includes('--production');

function parseEnvFile(filePath) {
  if (!fs.existsSync(filePath)) {
    return {};
  }

  const vars = {};
  for (const line of fs.readFileSync(filePath, 'utf8').split('\n')) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith('#')) {
      continue;
    }

    const separator = trimmed.indexOf('=');
    if (separator === -1) {
      continue;
    }

    const key = trimmed.slice(0, separator).trim();
    let value = trimmed.slice(separator + 1).trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    vars[key] = value;
  }
  return vars;
}

const env = {
  ...parseEnvFile(path.join(root, '.env')),
  ...parseEnvFile(path.join(root, '.env.local')),
  ...process.env,
};

const apiBaseUrl = env.API_BASE_URL || 'http://localhost:8000/api/v1';
const frontendUrl = env.FRONTEND_URL || 'http://localhost:4200';

const output = `// Auto-generated by scripts/generate-environment.mjs — do not edit manually.
// Copy .env.example to .env and run npm start / npm run build.

export const environment = {
  production: ${isProd},
  apiBaseUrl: '${apiBaseUrl.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',
  frontendUrl: '${frontendUrl.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}',
};
`;

const outPath = path.join(root, 'src/environments/environment.ts');
fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, output);
console.log(`Generated ${outPath} (production=${isProd})`);
